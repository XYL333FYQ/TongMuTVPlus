"""Require actual saved bytes, original playing media/document and foreign-frame denial."""
import json
import pathlib
import sys


def verify(log, generated, posted, api=34):
    rows = [json.loads(line.split(' ', 1)[1]) for line in log.splitlines() if line.startswith('CONTENT_EXPORT_REPORT ')]
    assert rows and all(row['origin'] > 0 for row in rows), 'Missing content export reports'
    assert len({(row['doc'], row['origin']) for row in rows}) == 1, 'Content export replaced its document'
    assert all(row['sameAudio'] for row in rows), 'Content export replaced its audio'
    events = {row['event'] for row in rows}
    assert {'ready', 'playing', 'Export-cancelled', 'Export-queued', 'Slow export-cancelled', 'POST export-queued', 'foreign'} <= events, 'Missing native export stages'
    assert 'failed' not in events, 'Content export failed'
    assert sum(row['event'] == 'Export-cancelled' for row in rows) >= (2 if api < 29 else 1), 'Missing cancellation or storage denial'
    completed = [row for row in rows if row['event'] in ('Export-queued', 'POST export-queued')]
    assert len(completed) == 2 and all(not row['paused'] for row in completed), 'Export stopped playback or completed twice'
    assert completed[1]['advance'] > completed[0]['advance'], 'Decoded media did not advance between saves'
    foreign = [row['extra'] for row in rows if row['event'] == 'foreign']
    assert foreign and all(row['native'] and not row['exportApi'] and not row['parentReadable'] for row in foreign), 'Foreign frame was not isolated'
    assert 'CONTENT_EXPORT_AUTHENTICATED True' in log and 'CONTENT_EXPORT_AUTHENTICATED False' not in log, 'POST lost browser authentication'
    assert generated == bytes(index % 251 for index in range(131079)) + '桐木导出'.encode(), 'Generated bytes changed'
    assert posted == bytes([0, 255, 1, 0]) + 'authenticated POST blob\n桐木'.encode(), 'POST bytes changed'
    return {'originalDocument': True, 'originalPlayingAudio': True, 'foreignFrameDenied': True, 'generatedBytes': len(generated), 'authenticatedPostBytes': len(posted)}


if __name__ == '__main__':
    result = verify(pathlib.Path(sys.argv[1]).read_text(), pathlib.Path(sys.argv[2]).read_bytes(), pathlib.Path(sys.argv[3]).read_bytes(), int(sys.argv[5]))
    pathlib.Path(sys.argv[4]).write_text(json.dumps(result, indent=2))
    print('PASS: consent/cancellation, actual Blob and authenticated POST bytes, same playing document/audio and foreign-frame isolation')
